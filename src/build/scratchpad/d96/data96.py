def mudraf(v, mn, fa=ANA, a_fa=A_ANA, pu='', p=None, sa=False, kana=False):
    """أُرِيدُ، تَعْرِفُ، سَتَدْرُسُ، سَأَلْتَحِقُ، وَيَجِبُ"""
    k0, a0 = pre(p) if p else ([], [])
    if sa:
        k0, a0 = k0 + [hk('سَ')], a0 + [ha('سَ')]
    base = v[len(p or ''):][2:] if sa else v[len(p or ''):]
    uz = ('ноқис ' if kana else '') + MRF + (', ' + fa if fa else '')
    ar = (A_MRF.replace('فِعْلٌ مُضَارِعٌ', 'فِعْلٌ مُضَارِعٌ نَاقِصٌ') if kana else A_MRF) + ('، ' + a_fa if a_fa else '.')
    pre_ty = 'و — ҳарф + ' if p else ''
    return W(v, 'R', pre_ty + ('Ҳарф + феъл' if sa else 'Феъл'), ('Ноқис музорий' if kana else 'Музорий') + ' феъли, раф', mn,
             k0 + [[base, uz]], ('ҳарф + ' if (sa or p) else '') + 'муз.феъли', 'R', a0 + [[base, ar]], pu=pu)


