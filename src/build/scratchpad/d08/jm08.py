def ibt(t):
    return ('«' + t + '» — ибтидоий жумла, ' + NA + '.', 'وَجُمْلَةُ «' + t + '» ابْتِدَائِيَّةٌ ' + LM)
def ist(t):
    return ('«' + t + '» — истеъноф жумласи (янги гап), ' + NA + '.', 'وَجُمْلَةُ «' + t + '» اسْتِئْنَافِيَّةٌ ' + LM)
