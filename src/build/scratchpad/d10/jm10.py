# 10-dars: jumlalarning e'robdagi o'rni ("ЖУМЛА" bloki)
LM = 'لَا مَحَلَّ لَهَا مِنَ الْإِعْرَابِ.'
def ibt(t, note=''):
    return ('«' + t + '» — ибтидоий жумла' + note + ', ' + NA + '.',
            'وَجُمْلَةُ «' + t + '» ابْتِدَائِيَّةٌ ' + LM)
def ist(t):
    return ('«' + t + '» — истеъноф жумласи (янги гап), ' + NA + '.',
            'وَجُمْلَةُ «' + t + '» اسْتِئْنَافِيَّةٌ ' + LM)
def atf(a, b):
    return ('«' + a + '» жумласи «' + b + '» жумласига маътуф, ' + NA + '.',
            'وَجُمْلَةُ «' + a + '» مَعْطُوفَةٌ عَلَى جُمْلَةِ «' + b + '» ' + LM)
JM = {
 '1-0': ibt('اَلسَّلَامُ عَلَيْكُمْ', ' (суҳбат шу билан бошланади)'),
 '2-0': atf('عَلَيْكُمُ السَّلَامُ', 'اَلسَّلَامُ عَلَيْكُمْ'),
 '3-0': ibt('أَيْنَ تَسْكُنُ'),
 '4-0': ibt('أَسْكُنُ فِي حَيِّ الْمَطَارِ'), '4-4': ist('أَيْنَ تَسْكُنُ أَنْتَ'),
 '5-0': ibt('أَسْكُنُ فِي حَيِّ الْجَامِعَةِ'),
 '6-0': ibt('هَلْ تَسْكُنُ فِي بَيْتٍ'),
 '7-1': ibt('أَسْكُنُ فِي بَيْتٍ', ' (жавоб ҳарфидан кейин)'), '7-4': ist('هَلْ تَسْكُنُ فِي بَيْتٍ'),
 '8-1': ibt('أَسْكُنُ فِي شَقَّةٍ', ' (жавоб ҳарфидан кейин)'),
 '9-0': ibt('مَا رَقْمُ شَقَّتِكَ'),
 '10-0': ibt('(رَقْمُ شَقَّتِي) خَمْسَةٌ'), '10-1': ist('مَا رَقْمُ بَيْتِكَ'),
 '11-0': ibt('(رَقْمُ بَيْتِي) تِسْعَةٌ'),
}
def apply_jm(IRB):
    for k, (uz, ar) in JM.items():
        e = IRB[k]; e['jm'] = uz
        if ar: e['a'] = e['a'] + [['', ar]]
