A_HUWA = 'وَالْفَاعِلُ ضَمِيرٌ مُسْتَتِرٌ جَوَازًا تَقْدِيرُهُ: هُوَ.'


def al(v):
    return v.replace('ال', 'اَل', 1) if v.startswith('ال') else v


def af5w(v, root, mn, kn, an_role, pre=None, case='R', pu=''):
    """ko'plik fe'li (يَفْعَلُونَ) — raf: ن saqlanadi; و — fo'il"""
    pk = {'وَ': K_WA, 'فَ': ['فَ', 'атф ҳарфи (кетма-кетлик, «шу сабаб»), фатҳага мабний, ' + NA]}
    pa = {'وَ': A_WA, 'فَ': ['الْفَاءُ', 'حَرْفُ عَطْفٍ مَبْنِيٌّ عَلَى الْفَتْحِ ' + LAMAHAL + '.']}
    k = ([pk[pre]] if pre else []) + [[root, 'музорий феъли, раф қилинган, аломати ن нинг собит бўлиши, чунки у афъоли хамсадан'],
                                      ['و', 'жамъ вови — муттасил замир бўлиб фоил, сукунга мабний, раф ўринда'], n(kn)]
    a = ([pa[pre]] if pre else []) + [[root, 'فِعْلٌ مُضَارِعٌ مَرْفُوعٌ وَعَلَامَةُ رَفْعِهِ ثُبُوتُ النُّونِ لِأَنَّهُ مِنَ الْأَفْعَالِ الْخَمْسَةِ، وَوَاوُ الْجَمَاعَةِ ضَمِيرٌ مُتَّصِلٌ مَبْنِيٌّ عَلَى السُّكُونِ فِي مَحَلِّ رَفْعٍ فَاعِلٌ، ' + an_role]]
    ty = ({'وَ': 'و — атф ҳарфи + ', 'فَ': 'ف — атф ҳарфи + '}[pre] if pre else '') + 'Феъл (мудори)'
    return W(v, 'M', ty, 'Марфуъ: афъоли хамса, раф белгиси ن нинг сақланиши; و — фоил', mn, k,
             ('ҳарф + ' if pre else '') + 'муз.феъли', 'R', a, pu=pu)


def isim_kana(v, verb, mn, gh=False, pu=''):
    return W(v, 'R', 'Исм', verb + ' нинг исми', mn,
             [[al(v), verb + ' нинг исми, раф қилинган, аломати зоҳирий замма']], 'исми', 'R',
             [[v, 'اسْمُ «' + verb + '» مَرْفُوعٌ وَعَلَامَةُ رَفْعِهِ الضَّمَّةُ الظَّاهِرَةُ.']], pu=pu)


def fail(v, verb, mn, pu=''):
    return W(v, 'R', 'Исм', 'Фоил', mn,
             [[al(v), 'фоил, раф қилинган, аломати зоҳирий замма'], n(verb + ' нинг фоили')], 'фоил', 'R',
             [[v, 'فَاعِلٌ مَرْفُوعٌ وَعَلَامَةُ رَفْعِهِ الضَّمَّةُ الظَّاهِرَةُ.']], pu=pu)


def sifa(v, mawsuf, mn, case, pu='', mudaf=False):
    nm = {'R': ('раф', 'замма', 'مَرْفُوعَةٌ وَعَلَامَةُ رَفْعِهَا الضَّمَّةُ'),
          'N': ('насб', 'фатҳа', 'مَنْصُوبَةٌ وَعَلَامَةُ نَصْبِهَا الْفَتْحَةُ'),
          'J': ('жар', 'касра', 'مَجْرُورَةٌ وَعَلَامَةُ جَرِّهَا الْكَسْرَةُ')}[case]
    return W(v, case, 'Исм (сифат)', 'Сифат: мавсуфга (' + mawsuf + ') эргашади' + (', мудоф' if mudaf else ''), mn,
             [[al(v), ('музоф бўлиб ' if mudaf else '') + 'сифат, ' + nm[0] + ' қилинган, аломати зоҳирий ' + nm[1]], n(mawsuf + ' нинг сифати')], 'сифат', case,
             [[v, 'صِفَةٌ ' + nm[2] + ' الظَّاهِرَةُ' + ('، وَهُوَ مُضَافٌ' if mudaf else '') + '.']], pu=pu)


def madi_f(v, mn, hid='هُوَ', pre=None, kn=None, pu='', naqis=False):
    """o'tgan zamon, fathaga mabniy"""
    k = ([K_WA] if pre == 'وَ' else []) + [[v.replace('وَ', '', 1) if pre else v,
          ('ноқис ' if naqis else '') + 'мозий феъли, фатҳага мабний' + (', тагида жоиз ҳолдаги ' + hid + ' мустатир замир бор бўлиб, у ' + ('унинг исми' if naqis else 'фоил') if hid else '')]]
    if kn:
        k.append(n(kn))
    base = v.replace('وَ', '', 1) if pre else v
    a = ([A_WA] if pre == 'وَ' else []) + [[base, 'فِعْلٌ مَاضٍ ' + ('نَاقِصٌ ' if naqis else '') + 'مَبْنِيٌّ عَلَى الْفَتْحِ' + ('، وَ' + ('اسْمُهُ' if naqis else 'الْفَاعِلُ') + ' ضَمِيرٌ مُسْتَتِرٌ جَوَازًا تَقْدِيرُهُ: ' + hid + '.' if hid else '.')]]
    ty = ('و — атф ҳарфи + ' if pre == 'وَ' else '') + 'Феъл (мозий' + (', ноқис' if naqis else '') + ')'
    s = ('ҳарф + ' if pre == 'وَ' else '') + ('ноқис феъл' if naqis else 'моз.феъли')
    return W(v, 'B', ty, 'Фатҳага мабний', mn, k, s if s != 'ҳарф + ноқис феъл' else 'ноқис феъл', '', a, pu=pu)


def asbaha(v, pre=False, ta=False, pu=''):
    k = ([K_WA] if pre else []) + [['أَصْبَحَ', 'ноқис мозий феъли (كَانَ нинг синглиси, «… бўлиб қолди, … а бошлади»), фатҳага мабний']]
    a = ([A_WA] if pre else []) + [['أَصْبَحَ', 'فِعْلٌ مَاضٍ نَاقِصٌ مَبْنِيٌّ عَلَى الْفَتْحِ' + ('،' if ta else '.')]]
    if ta:
        k.append(['تِ', 'таънис ҳарфи, сукунга мабний, кейинги ال билан 2 сукун йўлиқмаслиги учун касра қилинган, ' + NA])
        a[-1][1] += ' وَالتَّاءُ تَاءُ التَّأْنِيثِ السَّاكِنَةُ حُرِّكَتْ بِالْكَسْرِ لِالْتِقَاءِ السَّاكِنَيْنِ، ' + LAMAHAL + '.'
    return W(v, 'B', ('و — атф ҳарфи + ' if pre else '') + 'Феъл (мозий, ноқис)', 'Фатҳага мабний. Исмини раф, хабарини насб қилади', 'бўлиб қолди; … а бошлади',
             k, 'ноқис феъл', '', a, pu=pu)


def jar_al(v, jar, mn, mut, case_note='', pu='', mudaf=False):
    """بِ/لِ + ism (yopishgan)"""
    jb = {'بِ': 'بِـ', 'لِ': 'لِـ'}[jar]
    base = v[len(jar):]
    k = [[jar, 'жар ҳарфи, касрага мабний, ' + NA],
         [base, ('музоф бўлиб ' if mudaf else '') + 'мажрур, ' + jar + ' сабаб жар қилинган, аломати зоҳирий касра']]
    if mut:
        k.append(n('жар ва мажрур шибҳи жумла бўлиб, ' + mut + ' мутааллиқ'))
    a = [[jar.replace('بِ', 'الْبَاءُ').replace('لِ', 'اللَّامُ'), 'حَرْفُ جَرٍّ مَبْنِيٌّ عَلَى الْكَسْرِ ' + LAMAHAL + '.'],
         [base.replace('لْ', 'الْ', 1) if base.startswith('لْ') else base,
          'اسْمٌ مَجْرُورٌ بِـ«' + jb.rstrip('ـ') + '» وَعَلَامَةُ جَرِّهِ الْكَسْرَةُ الظَّاهِرَةُ' + ('، وَهُوَ مُضَافٌ' if mudaf else '') + '.']]
    return W(v, 'J', 'Ҳарф + исм', 'Жарр ҳарфи + мажрур' + (', мудоф' if mudaf else ''), mn, k, 'мажрур', 'J', a, pu=pu)


def ha_mudilayh(base, case, role_uz, role_ar, mn, v, pron='هِ', pre=None, pu='', ty='Исм', s=None, extra=None):
    """X + هُ/هِ: ism (mudof) + olmosh"""
    nm = {'R': ('раф', 'замма', 'مَرْفُوعٌ وَعَلَامَةُ رَفْعِهِ الضَّمَّةُ'),
          'N': ('насб', 'фатҳа', 'مَنْصُوبٌ وَعَلَامَةُ نَصْبِهِ الْفَتْحَةُ'),
          'J': ('жар', 'касра', 'مَجْرُورٌ وَعَلَامَةُ جَرِّهِ الْكَسْرَةُ')}[case]
    hv = {'هِ': ('касрага', 'الْكَسْرِ'), 'هُ': ('заммага', 'الضَّمِّ')}[pron]
    k = (pre[0] if pre else []) + [[base, 'музоф бўлиб ' + role_uz + ', ' + nm[0] + ' қилинган, аломати зоҳирий ' + nm[1]],
                                   [pron, 'муттасил замир бўлиб музофун илайҳ, ' + hv[0] + ' мабний, жар ўринда']] + (extra or [])
    a = (pre[1] if pre else []) + [[base, role_ar + ' ' + nm[2] + ' الظَّاهِرَةُ، وَهُوَ مُضَافٌ.'],
                                   ['الْهَاءُ', 'ضَمِيرٌ مُتَّصِلٌ مَبْنِيٌّ عَلَى ' + hv[1] + ' فِي مَحَلِّ جَرٍّ مُضَافٌ إِلَيْهِ.']]
    return W(v, 'M', ty, role_uz[0].upper() + role_uz[1:] + ', мудоф. ' + pron + ' — олмош, мудоф илайҳ', mn, k, s or role_uz, case, a, pu=pu)
