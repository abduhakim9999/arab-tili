    if shart:
        uz = 'шарт маъносидаги зарф замон, сукунга мабний, насб ўринда, ўзи шибҳи жумла бўлиб, ' + mut_uz + ' мутааллиқ'
        ar = 'ظَرْفٌ لِمَا يُسْتَقْبَلُ مِنَ الزَّمَانِ، خَافِضٌ لِشَرْطِهِ، مَبْنِيٌّ عَلَى السُّكُونِ فِي مَحَلِّ نَصْبٍ، مُتَعَلِّقٌ ' + mut_ar + '.'
