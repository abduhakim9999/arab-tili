# 12-dars: jumlalarning e'robdagi o'rni ("ЖУМЛА" bloki)
LM = 'لَا مَحَلَّ لَهَا مِنَ الْإِعْرَابِ.'
def ibt(t, note=''):
    return ('«' + t + '» — ибтидоий жумла' + note + ', ' + NA + '.',
            'وَجُمْلَةُ «' + t + '» ابْتِدَائِيَّةٌ ' + LM)
def ist(t):
    return ('«' + t + '» — истеъноф жумласи (янги гап), ' + NA + '.',
            'وَجُمْلَةُ «' + t + '» اسْتِئْنَافِيَّةٌ ' + LM)
def atf(a, b):
    return ('«' + a + '» жумласи «' + b + '» жумласига маътуф, ' + NA + '.',
            'وَجُمْلَةُ «' + a + '» مَعْطُوفَةٌ عَلَى جُمْلَةِ «' + b + '» ' + LM)
JM = {
 '1-0': ibt('اَلسَّلَامُ عَلَيْكُمْ', ' (суҳбат шу билан бошланади)'),
 '2-0': atf('عَلَيْكُمُ السَّلَامُ', 'اَلسَّلَامُ عَلَيْكُمْ'), '2-2': ist('(تُرِيدُ) أَيَّ خِدْمَةٍ'),
 '3-0': ibt('أُرِيدُ بَعْضَ الْأَثَاثِ'),
 '4-0': ibt('مَاذَا تُرِيدُ لِغُرْفَةِ النَّوْمِ'),
 '5-0': ibt('أُرِيدُ سَرِيرًا وَسِتَارَةً'),
 '6-0': ist('مَاذَا تُرِيدُ لِغُرْفَةِ الْجُلُوسِ'),
 '7-0': ibt('أُرِيدُ أَرِيكَةً وَسَجَّادَةً'),
 '8-0': ist('مَاذَا تُرِيدُ لِلْمَطْبَخِ'),
 '9-0': ibt('أُرِيدُ فُرْنًا وَثَلَّاجَةً'),
 '10-0': ist('مَاذَا تُرِيدُ لِلْحَمَّامِ'),
 '11-0': ibt('أُرِيدُ سَخَّانًا وَمِرْآةً'), '11-3': ist('أُرِيدُ مُشَاهَدَةَ الْأَثَاثِ'),
 '12-0': ibt('تَفَضَّلْ'),
}
def apply_jm(IRB):
    for k, (uz, ar) in JM.items():
        e = IRB[k]; e['jm'] = uz
        if ar: e['a'] = e['a'] + [['', ar]]
