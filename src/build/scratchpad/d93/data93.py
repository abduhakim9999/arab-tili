def pre(p):
    return ([hk(p, 'وَ' if p.startswith('وَ') else 'فَ')], [ha(p)]) if p else ([], [])

def verb(v, base, uz, ar, mn, p=None, objs=(), notes=(), s='моз.феъли', c='B', j='', pu='', ty=None, r=None, o=None):
    """objs: [(zamir, uz_role_text, ar_text)]"""
    k0, a0 = pre(p)
    k = k0 + [[base, uz]] + [[z, t] for z, t, _ in objs] + [n(x) for x in notes]
    a = a0 + [[base, ar]] + [[z if not z.startswith('ه') else 'الْهَاءُ' if z in ('هُ', 'هِ') else z, x] for z, _, x in objs]
    return W(v, c, ty or (('و — ҳарф + ' if p and p.startswith('وَ') else 'ф — ҳарф + ' if p else '') + 'Феъл'), r or uz.split(',')[0], mn,
             k, ('ҳарф + ' if p else '') + s, j, a, pu=pu, o=o)

