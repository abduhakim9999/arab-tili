def topics(li, wi, w):
    t = []
    txt = w['ty'] + ' ' + w['r'] + ' ' + ' '.join(x[1] for x in w['k'])
    v = w['v']
    if 'ғайри мунсариф' in txt: t.append('GHAYR')
    if 'афъоли хамса' in txt: t.append('AF5')
    if 'мусанно' in txt: t.append('MUTANNA')
    if 'لَكِنَّ' in v: t.append('LAKINNA')
    if v in ('أَنْ',) or 'أَنْ дан кейин' in txt: t += ['NASB', 'MASDARM']
    if 'ноқис' in txt or 'كَانَ нинг' in txt or (w['s'] == 'хабари'): t.append('KANA' if 'бошлаш' not in txt else 'SHURU')
    if 'أَخَذَتْ нинг' in txt or 'бошлаш феъли' in txt: t.append('SHURU')
    if 'لَمْ' in v or 'жазм' in txt or v == 'تَسْتَطِيعُ': t.append('JAZM')
    if 'мулҳақ' in txt or 'сон)' in w['ty']: t.append('ADAD')
    if w['s'] == 'тамйиз': t += ['TAMYIZ', 'ADAD']
    if 'истифҳом' in w['ty']: t.append('ISTIF')
    if w['s'] == 'зарф': t.append('ZARF')
    if 'мутлақ' in txt: t.append('MUTLAQ')
    if 'ишора' in w['ty']: t.append('ISHARA')
    if w['s'] == 'бадал': t.append('BADAL')
    if 'жамъ муаннас' in txt: t.append('JMS')
    if 'ҳол вови' in txt: t.append('WAWHAL')
    if v.startswith('فَ'): t.append('FA')
    if w['s'] in ('мубтадо', 'хабар', 'ҳарф + мубтадо'): t.append('MUBXAB')
    if w['s'] == 'фоил': t.append('FAIL')
    if w['s'] == 'маф.биҳ': t.append('MAFUL')
    if w['s'] == 'сифат': t.append('SIFAT')
    if 'маътуф' in w['s']: t.append('ATF')
    if w['s'] in ('жар ҳарфи', 'мажрур'): t.append('JARR')
    if 'муз.илайҳ' in w['s'] or 'музофун илайҳ' in txt: t.append('IDAFA')
    if w['s'].endswith('муз.феъли') and w['j'] == 'R': t.append('MUDRAF')
    if 'ҳол бўлиб' in txt or w['s'] == 'ҳол': t.append('HAL')
    out = []
    for x in t:
        if x not in out and x in qt: out.append(x)
    return out[:3]

