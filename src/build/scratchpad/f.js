const STOP = new Set(['қилм','бўлм','берм','олмо','келм','кетм','бери','қили','қилд','бўлд','берд','олди','келд','кетд','этди','этмо']);
function stems(s){ const r = new Set(); (s.toLowerCase().match(/[а-яёўқғҳ]+/g) || []).forEach(w => { if (w.length >= 4){ const st = w.slice(0, 4); if (!STOP.has(st)) r.add(st); } }); return r; }
function atoms(s){ return new Set(s.toLowerCase().split(/\s*\d\.\s*|•|;|,|—/).map(x => x.replace(/[().…]/g, '').replace(/\s+/g, ' ').trim()).filter(x => x.length > 1)); }
function overlap(a, b){ if (a === b) return true; const A = stems(a); for (const x of stems(b)) if (A.has(x)) return true;
  const P = atoms(a); for (const x of atoms(b)) if (P.has(x)) return true; return false; }
const baseM = m => m.replace(/\s*\.{2,}\s*$/, '');   // أَخَذَ va أَخَذَ ... bir-biriga variant bo'lmasin
function otherMeanings(idx, k){
  const mine = meaning(ITEMS[idx]); const out = [];
  for (const j of shuffle(ITEMS.map((_, i) => i))){
    if (j === idx || baseM(ITEMS[j].m) === baseM(ITEMS[idx].m)) continue; const m = meaning(ITEMS[j]);
    if (overlap(mine, m) || out.some(x => overlap(x, m))) continue;
    out.push(m); if (out.length === k) break;
  }
  return out;
}
const hasForms = i => !!ITEMS[i].mu;
function similarItems(idx, k){
  const it = ITEMS[idx], pre = it.mu.slice(0, 2), len = it.mu.length;
  const sc = j => (ITEMS[j].mu.slice(0, 2) === pre ? 0 : 2) + Math.abs(ITEMS[j].mu.length - len) / 4 + Math.random();
  return ITEMS.map((_, j) => j).filter(j => j !== idx && hasForms(j) && ITEMS[j].mu !== it.mu)
    .map(j => [j, sc(j)]).sort((a, b) => a[1] - b[1]).slice(0, k).map(x => x[0]);
}
// ma'no savoli: moziy beriladi, 3 ma'nodan biri
function tqMeaning(idx){
  const right = meaning(ITEMS[idx]);
  const opts = shuffle([right, ...otherMeanings(idx, 2)]);
  return { i: idx, k: 'm', o: opts.map(m => ({ me: m })), a: opts.indexOf(right) };
}
// sig'a savoli: noto'g'ri qatorlarda bitta shakl o'zgartirilgan
function tqForms(idx){
  const it = ITEMS[idx];
  const base = { mu: it.mu, am: it.am, ms: it.ms };
  const keys = shuffle(Object.keys(it.v)), wrong = [];
  keys.forEach(k => { const o = Object.assign({}, base); o[k] = it.v[k]; wrong.push(o); });
  if (wrong.length < 2 && keys.length >= 2){ const o = Object.assign({}, base); keys.slice(0, 2).forEach(k => o[k] = it.v[k]); wrong.push(o); }
  if (wrong.length < 2) similarItems(idx, 2 - wrong.length).forEach(j => wrong.push({ mu: ITEMS[j].mu, am: ITEMS[j].am, ms: ITEMS[j].ms }));
  const sh = shuffle([base, ...wrong.slice(0, 2)]);
  return { i: idx, k: 's', o: sh, a: sh.indexOf(base) };
}
function makeTestQs(p){
  const ids = setIdx(p);
  return [...shuffle(ids).map(tqMeaning), ...shuffle(ids.filter(hasForms)).map(tqForms)];
}

