# 4-dars: jumlalarning e'robdagi o'rni ("ЖУМЛА" bloki)
LM = 'لَا مَحَلَّ لَهَا مِنَ الْإِعْرَابِ.'
def ibt(t, note=''):
    return ('«' + t + '» — ибтидоий жумла' + note + ', ' + NA + '.',
            'وَجُمْلَةُ «' + t + '» ابْتِدَائِيَّةٌ ' + LM)
def atf(a, b):
    return ('«' + a + '» жумласи «' + b + '» жумласига маътуф, ' + NA + '.',
            'وَجُمْلَةُ «' + a + '» مَعْطُوفَةٌ عَلَى جُمْلَةِ «' + b + '» ' + LM)
JM = {
 '1-0': ibt('اَلسَّلَامُ عَلَيْكُمْ', ' (суҳбат шу билан бошланади)'),
 '2-0': atf('عَلَيْكُمُ السَّلَامُ', 'اَلسَّلَامُ عَلَيْكُمْ'),
 '3-0': ibt('مِنْ أَيْنَ أَنْتِ'),
 '4-0': ibt('أَنَا مِنْ مِصْرَ'),
 '5-0': ibt('هَلْ أَنْتِ مِصْرِيَّةٌ'),
 '6-1': ibt('أَنَا مِصْرِيَّةٌ', ' (жавоб ҳарфидан кейин)'),
 '6-3': atf('مَا جِنْسِيَّتُكِ أَنْتِ', 'أَنَا مِصْرِيَّةٌ'),
 '7-0': ibt('أَنَا سُورِيَّةٌ'),
 '7-2': ibt('أَنَا مِنْ سُورِيَا', ' (янги гап)'),
 '8-0': ibt('(جِئْتَ) أَهْلًا'),
 '8-1': atf('(وَطِئْتَ) سَهْلًا', '(جِئْتَ) أَهْلًا'),
}
def apply_jm(IRB):
    for k, (uz, ar) in JM.items():
        e = IRB[k]; e['jm'] = uz
        if ar: e['a'] = e['a'] + [['', ar]]
    IRB['6-3']['o'] = [['✅ Саҳифада шу:', 'وَ — атф ҳарфи («…чи»); жумла олдинги жумлага маътуф.'],
                       ['↔️ Бошқа фикр:', 'Сўроқ гап дарак гапга атф қилинмайди, шунинг учун وَ — истиъноф ҳарфи, жумла истиънофий.']]
