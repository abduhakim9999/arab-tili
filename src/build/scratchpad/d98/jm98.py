XA = {}
def apply_jm(IRB):
    for k, t in XA.items():
        IRB[k]['a'] = IRB[k]['a'] + [['', t]]
    for k, e in IRB.items():  # «ўзи мавсуф» → «وَهُوَ مَوْصُوفٌ»
        if any(not x[0] and x[1] == 'ўзи мавсуф' for x in e['k']) or any(x[0] and x[1].endswith('ўзи мавсуф') for x in e['k']):
            e['a'] = e['a'] + [['', 'وَهُوَ مَوْصُوفٌ.']]
        if any(not x[0] and x[1] == 'ўзи мубдалин минҳу' for x in e['k']):
            e['a'] = e['a'] + [['', 'وَهُوَ مُبْدَلٌ مِنْهُ.']]
    for k, (uz, ar) in JM.items():
        e = IRB[k]; e['jm'] = uz
        if ar: e['a'] = e['a'] + [['', ar]]
