const CYR_MAP = {a:'а',b:'б',d:'д',f:'ф',g:'г',h:'ҳ',i:'и',j:'ж',k:'к',l:'л',m:'м',n:'н',o:'о',p:'п',q:'қ',r:'р',s:'с',t:'т',u:'у',v:'в',x:'х',y:'й',z:'з',c:'ц',w:'в'};
const APOS = "'’‘ʻʼ`", VOW = 'aeiouAEIOU';
function cyrWord(w){
  let out = '';
  for (let i = 0; i < w.length; i++){
    const ch = w[i], lo = ch.toLowerCase(), nx = (w[i + 1] || '').toLowerCase();
    if ((lo === 'o' || lo === 'g') && nx && APOS.includes(nx)){ out += lo === 'o' ? 'ў' : 'ғ'; i++; continue; }
    if (lo === 's' && nx === 'h'){ out += 'ш'; i++; continue; }
    if (lo === 'c' && nx === 'h'){ out += 'ч'; i++; continue; }
    if (lo === 'y' && nx === 'o' && APOS.includes(w[i + 2] || '-')){ out += 'й'; continue; }
    if (lo === 'y' && nx && 'oaue'.includes(nx)){ out += {o:'ё', a:'я', u:'ю', e:'е'}[nx]; i++; continue; }
    if (lo === 'e'){ const prev = w[i - 1] || ''; out += !prev || VOW.includes(prev) ? 'э' : 'е'; continue; }
    if (APOS.includes(ch)){ out += i > 0 ? 'ъ' : ''; continue; }
    out += CYR_MAP[lo] || ch;
  }
  return out;
}
const cyr = s => s.replace(/[A-Za-z][A-Za-z'’‘ʻʼ`]*/g, cyrWord);

