def jarz(v, j, z, zuz, zar, mn, mut, pu='', p=None, jkey=None):
    """jar harfi + olmosh: فِيهَا، لَهُ، بِهِمَا ..."""
    k0, a0 = pre(p)
    k = k0 + [hk(jkey or j, j), [z, 'муттасил замир бўлиб мажрур, ' + zuz + ', жар ўринда'], n('жар ва мажрур шибҳи жумла бўлиб, ' + mut + ' мутааллиқ')]
    a = a0 + [ha(jkey or j), [z, 'ضَمِيرٌ مُتَّصِلٌ مَبْنِيٌّ عَلَى ' + zar + ' فِي مَحَلِّ جَرٍّ بِحَرْفِ الْجَرِّ.']]
    return W(v, 'B', ('ҳарф + ' if p else '') + 'Ҳарф ва олмош', 'Жар ҳарфи + олмош (жар ўринда)', mn, k, 'мажрур', '', a, pu=pu)

def jarn(v, j, base, mn, mut, pu='', mudaf=False, zam=None, case_note='', jkey=None, extra=()):
    """jar harfi + ism (+olmosh): بِسَبَبِ، بِيَدِهِ، لِأَصْحَابِهِ"""
    k = [hk(jkey or j, j), [al(base), ('музоф бўлиб ' if mudaf else '') + 'мажрур, ' + j + ' сабаб жар қилинган, аломати зоҳирий касра' + case_note]]
    a = [ha(jkey or j), [base, 'اسْمٌ مَجْرُورٌ وَعَلَامَةُ جَرِّهِ الْكَسْرَةُ الظَّاهِرَةُ' + ('، وَهُوَ مُضَافٌ' if mudaf else '') + '.']]
    if zam:
        k.append([zam[0], 'муттасил замир бўлиб музофун илайҳ, ' + zam[1] + ', жар ўринда'])
        a.append([zam[0], 'ضَمِيرٌ مُتَّصِلٌ مَبْنِيٌّ عَلَى ' + zam[2] + ' فِي مَحَلِّ جَرٍّ مُضَافٌ إِلَيْهِ.'])
    k += [n(x) for x in extra]
    k.append(n('жар ва мажрур шибҳи жумла бўлиб, ' + mut + ' мутааллиқ'))
    return W(v, 'J', 'Ҳарф + исм', 'Жар ҳарфи + мажрур' + (', мудоф' if mudaf else ''), mn, k, 'мажрур', 'J', a, pu=pu)

