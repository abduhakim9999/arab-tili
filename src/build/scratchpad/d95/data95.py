def fem(v, base, mn, kasra=False, p=None, kana=False, hid=False, objs=(), notes=(), pu=''):
    """نَشَأَتِ، كَانَتْ، أَثَّرَتِ، فَأَقْرَضَتْهَا، وَاقْتَرَضَتْ"""
    k0, a0 = pre(p)
    uz = (KANA if kana else MADI) + (', тагида жоиз ҳолдаги هِيَ мустатир замир бор бўлиб, у фоил' if hid else '')
    ar = (A_KANA if kana else A_MADI) + '.'
    k = k0 + [[base, uz], TAK if kasra else TAL] + [[z, t] for z, t, _ in objs] + [n(x) for x in notes]
    a = a0 + [[base, ar], A_TAK if kasra else A_TAL] + [['الْهَاءُ' if z == 'هَا' else z, x] for z, _, x in objs]
    if hid: a[-1 - len(objs)] = a[-1 - len(objs)]
    if hid: a.append(['', A_HIYA])
    s = ('ҳарф + ' if p else '') + ('ноқис феъл' if kana else 'моз.феъли')
    ty = ('ҳарф + ' if p else '') + ('Феъл (мозий, ноқис)' if kana else 'Феъл (мозий)')
    r = ('Ноқис мозий феъли, фатҳага мабний; ت — муаннаслик ҳарфи' if kana else 'Мозий феъли, фатҳага мабний; ت — муаннаслик ҳарфи')
    return W(v, 'B', ty, r, mn, k, s, '', a, pu=pu)


