def zarf(v, kind, mn, mut_uz, mut_ar, mudaf=True, pu=''):
    """بَعْدَ، الْيَوْمَ"""
    kn = 'зарф замон' if kind == 'z' else 'зарф макон'
    ka = 'ظَرْفُ زَمَانٍ' if kind == 'z' else 'ظَرْفُ مَكَانٍ'
    k = [[al(v), ('музоф бўлиб ' if mudaf else '') + kn + ', насб қилинган, аломати зоҳирий фатҳа, ўзи шибҳи жумла бўлиб, ' + mut_uz + ' га мутааллиқ']]
    a = [[v, ka + ' مَنْصُوبٌ وَعَلَامَةُ نَصْبِهِ الْفَتْحَةُ الظَّاهِرَةُ' + ('، وَهُوَ مُضَافٌ' if mudaf else '') + '، مُتَعَلِّقٌ بِـ«' + mut_ar + '».']]
    return W(v, 'N', 'Исм (' + kn + ')', kn[0].upper() + kn[1:] + (', мудоф' if mudaf else ''), mn, k, 'зарф', 'N', a, pu=pu)


