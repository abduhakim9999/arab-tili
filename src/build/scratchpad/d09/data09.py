# 9-dars (1-kitob, 2-bob «الأسرة»): бомдод азони — она, ота, Саъд, Саид.
L = []
UM = 'الْأُمُّ'
AB = 'الْأَبُ'
SD = 'سَعْدٌ'
SI = 'سَعِيدٌ'

def allah_akbar(pu):
    return [
        W('اللَّهُ', 'R', 'Исм (лафзи жалол)', 'Мубтадо', 'Аллоҳ',
          [['اللَّهُ', 'лафзи жалол, мубтадо, раф қилинган, аломати зоҳирий замма']], 'мубтадо', 'R',
          [['اللَّهُ', 'لَفْظُ الْجَلَالَةِ مُبْتَدَأٌ مَرْفُوعٌ وَعَلَامَةُ رَفْعِهِ الضَّمَّةُ الظَّاهِرَةُ.']]),
        xabar('أَكْبَرُ', 'улуғ', pu=pu, gm='wasf'),
    ]

def fi_jumla(name, mn_name, gm, place, mn_place, verb):
    # سَعْدٌ فِي الْحَمَّامِ يَتَوَضَّأُ
    return [mubtado(name, mn_name, gm=gm), jar('فِي', '…да'),
            majrur(place, mn_place, 'маҳзуф хабар бўлмиш كَائِنٌ', 'خَبَرٍ مَحْذُوفٍ تَقْدِيرُهُ: كَائِنٌ', maqsur=place == 'الْمُصَلَّى')] + verb

def fasl(v):
    return W(v, 'B', 'Исм (ажратиш замири)', 'Фатҳага мабний. Эъробдан ўрни йўқ', 'ўша',
             [[v, 'ажратиш (фасл) замири, фатҳага мабний, ' + NA],
              n('мубтадо билан хабар орасида келиб, кейинги сўз сифат эмас, хабар эканини кўрсатади ва уни таъкидлайди')], 'фасл замири', '',
             [[v, 'ضَمِيرُ فَصْلٍ مَبْنِيٌّ عَلَى الْفَتْحِ ' + LAMAHAL + '.']],
             o=[['✅ Саҳифада шу:', v + ' — ажратиш (фасл) замири, эъробдан ўрни йўқ; кейинги сўз — хабар.'],
                ['↔️ Бошқа фикр:', v + ' — иккинчи мубтадо, кейинги сўз унинг хабари; бу жумла биринчи мубтадонинг хабари (раф ўринда).']])

def hayya(pu):
    return [
        W('هَيَّا', 'B', 'Исм феъл (амр маъносида)', 'Сукунга мабний', 'қани, юринглар',
          [['هَيَّا', 'амр маъносидаги исм феъл («юринглар, тезланглар»), сукунга мабний, тагида вожиб ҳолдаги أَنْتُمْ мустатир замир бор бўлиб, у фоил'],
           n('исм феъл — шакли исм, иши феъл: амр феъли каби иш буюради, лекин турланмайди')], 'исм феъл', '',
          [['هَيَّا', 'اسْمُ فِعْلِ أَمْرٍ مَبْنِيٌّ عَلَى السُّكُونِ، وَالْفَاعِلُ ضَمِيرٌ مُسْتَتِرٌ وُجُوبًا تَقْدِيرُهُ: أَنْتُمْ.']]),
        W('بِنَا', 'B', 'Ҳарф ва олмош (بِ — жар ҳарфи, نَا — олмош)', 'بِ — касрага мабний; نَا — сукунга мабний, жар ўринда', 'биз билан',
          [['بِ', 'жар ҳарфи («… билан»), касрага мабний, ' + NA],
           ['نَا', 'муттасил замир бўлиб мажрур, сукунга мабний, жар ўринда'],
           n('жар ва мажрур шибҳи жумла бўлиб, هَيَّا га мутааллиқ')], 'мажрур', '',
          [['الْبَاءُ', 'حَرْفُ جَرٍّ مَبْنِيٌّ عَلَى الْكَسْرِ ' + LAMAHAL + '.'],
           ['نَا', 'ضَمِيرٌ مُتَّصِلٌ مَبْنِيٌّ عَلَى السُّكُونِ فِي مَحَلِّ جَرٍّ بِالْبَاءِ، وَالْجَارُّ وَالْمَجْرُورُ مُتَعَلِّقَانِ بِـ«هَيَّا».']], pu=pu),
    ]

