def nom(v, role, case, mn, mudaf=False, note=None, pu='', jar=None, mut=None, ty='Исм', r=None, extra_ar='', o=None):
    """oddiy ism: mubtado/xabar/fo'il/maf'ul/majrur/muzofun ilayh/sifat"""
    R = ROLE[role]
    role_uz = R[0] + (', ' + jar + ' сабаб жар қилинган' if jar else '')
    if jar:
        k = [[al(v), ('музоф бўлиб ' if mudaf else '') + 'мажрур, ' + jar + ' сабаб жар қилинган, аломати зоҳирий касра']]
        a = [[v, 'اسْمٌ مَجْرُورٌ بِـ«' + jar + '» وَعَلَامَةُ جَرِّهِ الْكَسْرَةُ الظَّاهِرَةُ' + ('، وَهُوَ مُضَافٌ' if mudaf else '') + extra_ar + '.']]
    else:
        k = [nk(v, R[0], case, mudaf)]
        a = [na(v, R[1], case, mudaf, extra_ar)]
    if mut: k.append(n('жар ва мажрур шибҳи жумла бўлиб, ' + mut + ' мутааллиқ'))
    if note: k.append(n(note))
    return W(v, case, ty, r or (R[0][0].upper() + R[0][1:] + (', мудоф' if mudaf else '')), mn, k, R[2], case, a, pu=pu, o=o)

