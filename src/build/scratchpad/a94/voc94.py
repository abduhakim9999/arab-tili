def dars():
    s = open(os.path.join(ROOT, '94.html'), encoding='utf-8').read()
    t = re.search(r'var D=(\[.*?\]);\n', s, re.S).group(1)
    rows = re.findall(r'\["(.*?)",`(.*?)`\]', t, re.S)
    D = [[x.split('|')[0] for x in w.split('/')] for sp, w in rows]
    TR = json.loads(re.search(r'var TR=(\[.*?\]);\n', s, re.S).group(1))
    return D, TR


def bolak(D, l, i):
    """(l, i) so'z turgan gap: tokenlar oralig'i [a, b)"""
    T = D[l]
    a = i
    while a > 0 and not re.search(r'~[.؟!]', T[a - 1]):
        a -= 1
    b = i
    while b < len(T) - 1 and not re.search(r'~[.؟!]', T[b]):
        b += 1
    return a, b + 1


def misol(D, TR, l, i, qism, uzm):
    T = D[l]
    a, b = bolak(D, l, i)
    ar = []
    for j in range(a, b):
        w, _, p = T[j].partition('~')
        if j == i:
            if qism:
                k = 0 if w.startswith(qism) else len(w) - len(qism) if w.endswith(qism) else w.find(qism)
                assert k >= 0, (l, i, qism, w)
                w = w[:k] + '{' + qism + '}' + w[k + len(qism):]
            else:
                w = '{' + w + '}'
        ar.append(w + (('' if p[:1] in '.،؟!' else ' ') + p if p else ''))
    uz = []
    hit = False
    for txt, ix in TR[l]:
        if min(ix) < a or min(ix) >= b:
            continue
        if not uzm and i in ix:
            m = re.match(r'^(.*?)([.,!?»”]*)$', txt)
            txt = '{' + m.group(1) + '}' + m.group(2)
            hit = True
        uz.append(txt)
    uz = ' '.join(uz)
    if uzm:
        if '{' in uzm:
            p = uzm.replace('{', '').replace('}', '')
            assert p in uz, (l, i, uzm, uz)
            uz = uz.replace(p, uzm, 1)
        else:                                   # qavssiz — shu qismning o'zi yashil
            assert uzm in uz, (l, i, uzm, uz)
            uz = uz.replace(uzm, '{' + uzm + '}', 1)
        hit = True
    assert hit, (l, i, uz)
    return [' '.join(ar).replace(' ~', ''), uz]


def egasi(D):
    """matndagi har o'rin (so'z oynasi) bitta yozuvga: qamrab olgan harflari ko'prog'i (بِالْمَعْهَدِ → مَعْهَدٌ, وَلَا → لَا);
    teng bo'lsa — harf, keyin zamir (فِيهَا → فِي)"""
    yal = lambda x: re.sub(r'[\u064B-\u0652\u0670\u0640~.،؟!()0-9]', '', x)
    E = {}
    for n, (yoz, uz, w, e) in enumerate(V):
        rk = 0 if yoz.startswith('.') else 1
        for x in w:
            k = '%d-%d' % (x[0], x[1])
            u = (len(yal(x[2] if len(x) > 2 else D[x[0]][x[1]].split('~')[0])), rk)
            if k not in E or u > E[k][0]:
                E[k] = (u, n)
    return {k: v[1] for k, v in E.items()}


def voc():
    D, TR = dars()
    EG = egasi(D)
    out = []
    for n, (yoz, uz, w, e) in enumerate(V, 1):
        e = dict(e)
        ex = e.pop('ex', None)
        uzm = e.pop('uzm', None)
        exw = e.pop('exw', 0)
        e.pop('mz', None)
        if ex is None:
            l, i = w[exw][0], w[exw][1]
            ex = [misol(D, TR, l, i, w[exw][2] if len(w[exw]) > 2 else None, uzm)]
        ww = ['%d-%d' % (x[0], x[1]) for x in w if EG['%d-%d' % (x[0], x[1])] == n - 1]
