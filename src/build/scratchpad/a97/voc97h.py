def eski():
    s = open(os.path.join(ROOT, '97.html'), encoding='utf-8').read()
    V0 = json.loads(re.search(r'var VOC=(\[.*?\]);\n', s, re.S).group(1))
    L = json.load(open(os.path.join(ROOT, 'data/lugat.json'), encoding='utf-8'))['s']
    M = json.load(open(os.path.join(ROOT, 'src/build/lugat-moziy.json'), encoding='utf-8'))
    ID = {r['yozuv']: r['id'] for r in L if r['d'] == 97}
    out = []
    for kn, yoz, uz, ex, e in V0:
        if not e.get('q') and (e.get('ay') or e.get('asl')):
            continue                                    # allaqachon yangi usulda (qayta ishga tushirilsa)
        d = {'ex': ex}
        if e.get('y'):
            d['y'] = e['y']
        if yoz in ID and str(ID[yoz]) in M:
            d['mz'] = M[str(ID[yoz])]
        w = [tuple(int(x) for x in k.split('-')) for k in e.get('w', [])]
        out.append((AMR.get(yoz, yoz), uz, w, d))
    return out


def kalit():
    """idlar.json: amr qo'shilgan fe'l kaliti yangi yozuvga (raqam o'sha)"""
    sys.path.insert(0, os.path.join(ROOT, 'src/build'))
    from ajrat import plain
    p = os.path.join(ROOT, 'src/build/idlar.json')
    I = json.load(open(p, encoding='utf-8'))
    n = 0
    for a, b in AMR.items():
        k0, k1 = '97|%s|1' % plain(a), '97|%s|1' % plain(b)
        if k0 in I['w'] and k1 not in I['w']:
            I['w'][k1] = I['w'].pop(k0); n += 1
    json.dump(I, open(p, 'w', encoding='utf-8'), ensure_ascii=False, indent=0, sort_keys=True)
    print('kalit:', n)


