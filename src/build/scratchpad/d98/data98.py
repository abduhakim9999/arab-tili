    k0, a0 = pre(p)
    k = k0 + [nk(base, R[0], case)] + ([n(note)] if note else [])
    a = a0 + [na(base, R[1], case)]
    sh = 'ф' if v.startswith('فَ') else 'و'
    return W(v, case, sh + ' — ҳарф + исм', R[0][0].upper() + R[0][1:], mn, k, 'ҳарф + ' + R[2], case, a, pu=pu, o=o)


