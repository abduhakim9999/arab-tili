# 7-dars: jumlalarning e'robdagi o'rni ("ЖУМЛА" bloki)
LM = 'لَا مَحَلَّ لَهَا مِنَ الْإِعْرَابِ.'
def ibt(t, note=''):
    return ('«' + t + '» — ибтидоий жумла' + note + ', ' + NA + '.',
            'وَجُمْلَةُ «' + t + '» ابْتِدَائِيَّةٌ ' + LM)
def ist(t):
    return ('«' + t + '» — истеъноф жумласи (янги гап), ' + NA + '.',
            'وَجُمْلَةُ «' + t + '» اسْتِئْنَافِيَّةٌ ' + LM)
def atf(a, b):
    return ('«' + a + '» жумласи «' + b + '» жумласига маътуф, ' + NA + '.',
            'وَجُمْلَةُ «' + a + '» مَعْطُوفَةٌ عَلَى جُمْلَةِ «' + b + '» ' + LM)
SILA = ('«شَاءَ اللَّهُ» — силатул мавсул жумласи, ' + NA + '.', 'وَجُمْلَةُ «شَاءَ اللَّهُ» صِلَةُ الْمَوْصُولِ ' + LM)
JM = {
 '1-0': ibt('اَلسَّلَامُ عَلَيْكُمْ', ' (суҳбат шу билан бошланади)'),
 '2-0': atf('عَلَيْكُمُ السَّلَامُ', 'اَلسَّلَامُ عَلَيْكُمْ'),
 '3-0': ibt('هَذِهِ صُورَةُ أُسْرَتِي'),
 '4-0': ibt('(هَذَا) مَا شَاءَ اللَّهُ'), '4-1': SILA,
 '4-3': ist('مَنْ هَذَا'),
 '5-0': ibt('هَذَا وَالِدِي عَدْنَانُ'), '5-3': ist('هُوَ مُهَنْدِسٌ'),
 '6-0': ist('مَنْ هَذِهِ'),
 '7-0': ibt('هَذِهِ وَالِدَتِي سَعِيدَةُ'), '7-3': ist('هِيَ طَبِيبَةٌ'),
 '8-0': ist('مَنْ هَذَا'),
 '9-0': ibt('هَذَا أَخِي عِيسَى'), '9-3': ist('هُوَ طَالِبٌ'),
 '10-0': ist('مَنْ هَذِهِ'),
 '11-0': ibt('هَذِهِ أُخْتِي عَبْلَةُ'), '11-3': ist('هِيَ مُعَلِّمَةٌ'),
 '11-5': ist('هَذَا جَدِّي'), '11-7': atf('هَذِهِ جَدَّتِي', 'هَذَا جَدِّي'),
 '12-0': ibt('(هَذَا) مَا شَاءَ اللَّهُ'), '12-1': SILA,
}
def apply_jm(IRB):
    for k, (uz, ar) in JM.items():
        e = IRB[k]; e['jm'] = uz
        if ar: e['a'] = e['a'] + [['', ar]]
