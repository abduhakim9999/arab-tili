def wa_(base_fn, kind='atf'):
    # وَهَذَا / وَهَذِهِ: kind='atf' (бир сўзловчи ичида) ёки 'ist' (янги гап боши)
    w = base_fn()
    if kind == 'atf':
        kk = ['وَ', 'атф ҳарфи («… эса»), фатҳага мабний, ' + NA]
        aa = ['الْوَاوُ', 'حَرْفُ عَطْفٍ مَبْنِيٌّ عَلَى الْفَتْحِ ' + LAMAHAL + '.']
        t = 'атф'
    else:
        kk = ['وَ', 'истеъноф ҳарфи («… эса»), фатҳага мабний, ' + NA]
        aa = ['الْوَاوُ', 'حَرْفُ اسْتِئْنَافٍ مَبْنِيٌّ عَلَى الْفَتْحِ ' + LAMAHAL + '.']
        t = 'истеъноф'
    w['k'] = [kk] + w['k']; w['a'] = [aa] + w['a']
    w['v'] = 'وَ' + w['v']; w['ty'] = 'و — ' + t + ' ҳарфи + ' + w['ty']
    w['s'] = 'ҳарф + мубтадо' if w['s'] == 'мубтадо' else 'ҳарф + ' + w['s']
    w['mn'] = w['mn'] + ' эса'
    return w

