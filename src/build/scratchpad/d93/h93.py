SILENT93 = {0}
SKIPW = {(16, 3), (17, 1)}          # (إِنَاءٌ) (فِرَاشٌ) — audioda o'qilmaydi
EXTRA = {(13, 4): ['لَهُ']}          # audioda «خَيْرٌ لَهُ» — vaqti خَيْرٌ ga qo'shiladi
SAW = ['صَلَّى', 'اللَّهُ', 'عَلَيْهِ', 'وَسَلَّمَ']
def align_tokens(L):
    out = []
    for li, (sp, ws, tr) in enumerate(L):
        if li in SILENT93: continue
        for wi, w in enumerate(ws):
            if (li, wi) in SKIPW: continue
            toks = SAW if w['v'] == 'ﷺ' else [w['v']]
            toks = toks + EXTRA.get((li, wi), [])
            out += [((li, wi), t) for t in toks]
    return out
