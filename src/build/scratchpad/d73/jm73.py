def apply_jm(IRB):
    for k, (uz, ar) in JM.items():
        e = IRB[k]
        e['k'] = [r for r in e['k'] if not (len(r) > 2 and r[2] == 'n' and JNOTE.search(r[1]))]
        e['jm'] = uz
        if ar:
            e['a'] = e['a'] + [['', ar]]
    for k in ('3-0', '8-0', '12-0', '6-0'):
        e = IRB[k]; assert e['k'][0][0] == 'وَ', k
        e['k'][0] = list(IBT_K); e['a'][0] = list(IBT_A)
    IRB['17-0']['k'][0][1] = IRB['17-0']['k'][0][1].replace('истинноф ҳарфи', 'ибтидо (истиъноф) ҳарфи')
    for k in ('14-1', '15-2'):
        for r in IRB[k]['a']:
            r[1] = r[1].replace('لَا مَحَلَّ لَهُ مِنَ', 'لَا مَحَلَّ لَهَا مِنَ')
