def addn(w, *notes, ar=None):
    """so'z yozuviga «↳» izoh (va arabcha e'rob qatori) qo'shadi"""
    w['k'] = w['k'] + [n(x) for x in notes]
    if ar: w['a'] = w['a'] + [['', ar]]
    return w


