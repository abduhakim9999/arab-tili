def nk(v, role, case, mudaf=False, extra=''):
    c = CASE[case]
    return [al(v), ('музоф бўлиб ' if mudaf else '') + role + ', ' + c[0] + ' қилинган, аломати зоҳирий ' + c[1] + extra]
