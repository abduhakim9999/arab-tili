def isml(v, verb, case, mn, pu='', note=None, muax=False, mudaf=False):
    """كَانَ нинг исми / хабари"""
    C = CASE[case]
    role = verb + ' нинг ' + ('исми' if case == 'R' else 'хабари') + (' муаххар' if muax else '')
    k = [[al(v), ('музоф бўлиб ' if mudaf else '') + role + ', ' + C[0] + ' қилинган, аломати зоҳирий ' + C[1]]] + ([n(note)] if note else [])
    ar_role = ('اسْمُ' if case == 'R' else 'خَبَرُ') + ' «' + verb + '»' + (' مُؤَخَّرٌ' if muax else '')
    a = [[v, ar_role + ' ' + C[2] + ('، وَهُوَ مُضَافٌ' if mudaf else '') + '.']]
    return W(v, case, 'Исм', role[0].upper() + role[1:], mn, k, 'исми' if case == 'R' else 'хабари', case, a, pu=pu)


