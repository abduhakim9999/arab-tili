def J(x):
    return json.dumps(x, ensure_ascii=False)

def rep_json(s, name, val):
    key = 'var ' + name + '='
    i = s.find(key)
    assert i >= 0 and s.count(key) == 1, name
    st = i + len(key)
    obj, end = json.JSONDecoder().raw_decode(s, st)
    return s[:st] + J(val) + s[end:]

