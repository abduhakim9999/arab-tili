import subprocess,glob,sys,re
T={50:'ноқис амр феъли',51:'таъкид ҳарфи',54:'зоида жар ҳарфи',56:'маҳзуф феълнинг ноиби',60:'музоф бўлиб мубтадо',61:'аломат ўрнининг',65:'насб аломати зоҳирий',67:'мафъулун мутлақ, насб',68:'мафъулун лиажлиҳ, насб',69:'вовул маъийя',70:'мунодо, заммага',71:'жумлаи ҳолийя',72:'тамйиз, насб',73:'ҳаср ҳарфи',74:'аломати нуннинг ҳазф',75:'феълдан изоҳланган',76:'насб ва жавоб',77:'жазм ҳарфи',79:'жазм ва талаб',80:'жазм ва наҳй',81:'ўзи мавсуф',89:'маътуф, раф',90:'таъкид, раф',91:'мубдалин минҳу',92:'замири мубтадога',93:'мубтадо муаххар'}
for n,p in T.items():
    f=[x for x in glob.glob(f'*{n}-д*.pdf')+glob.glob(f'*{n}-дарс.pdf')]
    f=f[0]
    np=int(re.search(r'Pages:\s+(\d+)',subprocess.run(['pdfinfo',f],capture_output=True,text=True).stdout).group(1))
    hit=None
    for i in range(1,np+1):
        t=subprocess.run(['pdftotext','-f',str(i),'-l',str(i),f,'-'],capture_output=True,text=True).stdout
        if p in re.sub(r'\s+',' ',t): hit=i;break
    print(n,f,np,hit)
